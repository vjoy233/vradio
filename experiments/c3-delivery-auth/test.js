'use strict';
const assert = require('assert');
const { createFakeProvider, createAdapter } = require('./fake-adapter');
const p = createFakeProvider(), other = createFakeProvider();
const revision = 'a'.repeat(40), paths = ['v2/pointer.json', 'v2/generation/manifest.json', 'v2/generation/data.json'];
const config = { repository: 'owner/repo', revision, paths };
const contents = Object.fromEntries(paths.map((path, i) => [path, Buffer.from('file' + i)]));
const evidence = p.issue(config.repository, revision, contents), adapter = createAdapter(config, p);
const session = adapter.open(evidence);
for (let i = 0; i < paths.length; i++) assert.strictEqual(session.read(paths[i]).toString(), 'file' + i);
contents[paths[0]][0] = 88;
const bytes = session.read(paths[0]); bytes[0] = 88;
assert.strictEqual(session.read(paths[0]).toString(), 'file0');
// 同 provider/repo/revision 可签发内容不同的假树；不能在一次 session 换证据。
const divergent = p.issue('owner/repo', revision, { [paths[0]]: Buffer.from('other'), [paths[1]]: Buffer.from('mixed') });
assert.strictEqual(adapter.open(divergent).read(paths[1]).toString(), 'mixed');
assert.strictEqual(session.read(paths[1]).toString(), 'file1');
assert.throws(() => session.read(divergent, paths[1]));
assert.throws(() => session.read(paths[1], divergent));
config.paths.push('v2/extra');
assert.throws(() => session.read('v2/extra'));
assert.throws(() => session.read('../v2/pointer.json'));
assert.throws(() => adapter.open({}));
assert.throws(() => adapter.open({ repository: 'owner/repo', revision, url: 'https://example/' + revision }));
assert.throws(() => adapter.open(other.issue('owner/repo', revision, contents)));
assert.throws(() => adapter.open(p.issue('owner/other', revision, contents)));
assert.throws(() => adapter.open(p.issue('owner/repo', 'b'.repeat(40), contents)));
assert.throws(() => adapter.open(p.issue('owner/repo', revision, {})).read(paths[0]));
assert.throws(() => createAdapter({ repository: 'owner/repo', revision: 'main', paths }, p));
assert.throws(() => createAdapter({ repository: 'owner/repo', revision, paths: ['v2/../x'] }, p));
assert.throws(() => createAdapter({ repository: 'owner/repo', revision, paths }, null));
assert.throws(() => createAdapter({ repository: 'owner/repo', revision, paths }, {}).open(evidence));
console.log('fake delivery adapter: offline checks passed');
