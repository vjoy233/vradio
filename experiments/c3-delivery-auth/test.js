'use strict';
const assert = require('assert');
const { createFakeProvider, createAdapter } = require('./fake-adapter');
const p = createFakeProvider(), other = createFakeProvider();
const revision = 'a'.repeat(40), paths = ['v2/pointer.json', 'v2/generation/manifest.json', 'v2/generation/data.json'];
const config = { repository: 'owner/repo', revision, paths };
const contents = Object.fromEntries(paths.map((path, i) => [path, Buffer.from('file' + i)]));
const evidence = p.issue(config.repository, revision, contents), adapter = createAdapter(config, p);
for (let i = 0; i < paths.length; i++) assert.strictEqual(adapter.read(evidence, paths[i]).toString(), 'file' + i);
contents[paths[0]][0] = 88;
const bytes = adapter.read(evidence, paths[0]); bytes[0] = 88;
assert.strictEqual(adapter.read(evidence, paths[0]).toString(), 'file0');
config.paths.push('v2/extra');
assert.throws(() => adapter.read(evidence, 'v2/extra'));
assert.throws(() => adapter.read(evidence, '../v2/pointer.json'));
assert.throws(() => adapter.read({}, paths[0]));
assert.throws(() => adapter.read({ repository: 'owner/repo', revision, url: 'https://example/' + revision }, paths[0]));
assert.throws(() => adapter.read(other.issue('owner/repo', revision, contents), paths[0]));
assert.throws(() => adapter.read(p.issue('owner/other', revision, contents), paths[0]));
assert.throws(() => adapter.read(p.issue('owner/repo', 'b'.repeat(40), contents), paths[0]));
assert.throws(() => adapter.read(p.issue('owner/repo', revision, {}), paths[0]));
assert.throws(() => createAdapter({ repository: 'owner/repo', revision: 'main', paths }, p));
assert.throws(() => createAdapter({ repository: 'owner/repo', revision, paths: ['v2/../x'] }, p));
assert.throws(() => createAdapter({ repository: 'owner/repo', revision, paths }, null));
assert.throws(() => createAdapter({ repository: 'owner/repo', revision, paths }, {}).read(evidence, paths[0]));
console.log('fake delivery adapter: offline checks passed');
